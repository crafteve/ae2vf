package io.github.crafteve.idlefactory.factory.io;

/**
 * 一次机器侧搬运尝试的结果原因。
 *
 * <p>它只回答「这一次尝试为什么是这个结果」，是账本行上的标签，也是执行器对上级的唯一回答。
 * 世界态（方块在不在、区块加载没加载）不在这里——那是 {@code MachineStatus} 的事；机器一旦
 * 离开表单，它的单元与账本一起释放，不会产生「不搬的原因」。</p>
 *
 * <p>{@link #RUN} 既包含「搬了」也包含「跑了但没量」，有没有量看账本行的数量字段。</p>
 */
public enum Reason {
    /** 这一轮正常执行。 */
    RUN,
    /** 执行层择时判定本轮不跑（连续空转，见单元的结论）。 */
    SLEEPING,
    /** 探不到可用的面。 */
    NO_FACE,
    /** 候选或探测预算耗尽，本轮没排上。 */
    BUDGET_OUT,
    /** 仓库或机器没有这个资源。 */
    NO_MATERIAL,
    /** 机器或仓库满了。 */
    FULL,
    /** 有容量却不收（面不对），当场清掉面记忆。 */
    REJECTED,
    /** 异常；退款失败也归这里。 */
    ERROR
}
